// Compile editorial JSON into a cacheable browser asset; no network at runtime.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const expansion = require('../data/healthcare-expansion.json');
const profiles = require('../data/healthcare-profiles.json');
const sections = require('../data/healthcare-sections.json').sections;
for (const extension of require('../data/healthcare-workflows.json')) {
  const section = sections.find(section => section.id === extension.section);
  if (!section) throw new Error('Unknown extension section: ' + extension.section);
  section.categories.push(...extension.categories);
}
const logos = require('../assets/health-plan-logos/provider-sources.json');
const logoOverrides = require('../data/healthcare-logo-overrides.json');
const html = fs.readFileSync(path.join(root, 'health-plan-landscape.html'), 'utf8');
const existingSources = [...html.matchAll(/<a\b[^>]*href="(https:[^"]+)"[^>]*>([\s\S]*?)<\/a>/g)].map(m => ({ url: m[1].replace(/&amp;/g, '&'), title: m[2].replace(/<[^>]+>/g, '').replace(/&amp;/g, '&') }));
const startups = new Set(['verifiable','medallion','redox','healthgorilla','zus','particle','1up','healthmine','carbon','elation','akasa','infinitus','smarterdx','fathom','coda','nym','cedar','nexhealth','luma','artera','abridge','ambience','suki','vizai','aidoc','tempus','qventus','leansystems','claroty','parachute','cadence','hrs']);
const newBrands = Object.fromEntries(expansion.brands.map(brand => [brand.id, {
  ...brand, logo: logos[brand.id]?.file || null,
  icon: logoOverrides[brand.id]?.icon ?? brand.icon ?? /favicon|apple-touch|webclip|site-icon|symbol|favicon|icon_logo|small-logo/i.test(logos[brand.id]?.url || ''),
  white: logoOverrides[brand.id]?.white ?? brand.white ?? /white|inverse|reverse|logo-Light|Logo-2c-White/i.test(logos[brand.id]?.url || ''),
  cohort: startups.has(brand.id) ? 'startup' : 'incumbent',
  sources: brand.sources || [{ url: brand.website, title: brand.sourceTitle || brand.name + ' — official overview' }],
}]));
const payload = { reviewed: expansion.reviewed, scope: expansion.scope, profiles, newBrands, sections, existingSources };
const output = '// Generated by scripts/build-healthcare-data.cjs. Edit data/healthcare-*.json instead.\n(function(root) {\n  const data = ' + JSON.stringify(payload) + ';\n  if (typeof module === "object" && module.exports) module.exports = data;\n  else root.HealthcareData = data;\n})(typeof window === "undefined" ? this : window);\n';
const outputPath = path.join(root, 'assets/healthcare-data.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(outputPath, 'utf8') !== output) throw new Error('Healthcare data asset is stale. Run npm run healthcare:build.');
} else fs.writeFileSync(outputPath, output);
console.log(`${Object.keys(newBrands).length} researched additions, ${sections.reduce((n, s) => n + s.categories.length, 0)} new categories`);
